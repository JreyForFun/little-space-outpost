#!/usr/bin/env python3
"""Download real solar events from NASA/CCMC DONKI and bundle them for offline play.

Usage:  python tools/fetch_donki.py [API_KEY]
Writes: src/data/donki-events.js   (window.OUTPOST_DONKI / module.exports)

Sources (NASA Open APIs, https://api.nasa.gov/ - public domain U.S. Government data):
  /DONKI/notifications?type=FLR  -> flare class, peak time, source region
  /DONKI/SEP                     -> solar energetic particle events and their linked flares
  /DONKI/GST                     -> geomagnetic storms (max Kp index)
"""
import json
import os
import re
import sys
import urllib.request
from datetime import date

KEY = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("NASA_API_KEY", "DEMO_KEY")
BASE = "https://api.nasa.gov/DONKI/"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "data", "donki-events.js")
RAW = os.path.join(os.path.dirname(__file__), "donki-raw")  # cached raw API responses (provenance)

# Historic storm periods replayed by the campaign.
WINDOWS = [
    {"id": "may2024", "title": "The May 2024 solar storms", "start": "2024-05-07", "end": "2024-05-20"},
    {"id": "oct2024", "title": "The October 2024 solar storms", "start": "2024-10-01", "end": "2024-10-12"},
    {"id": "sep2017", "title": "The September 2017 solar storms", "start": "2017-09-04", "end": "2017-09-12"},
]


def get(path, **params):
    name = path + "_" + "_".join(f"{k}-{v}" for k, v in sorted(params.items())) + ".json"
    cache = os.path.join(RAW, name)
    if os.path.exists(cache):
        with open(cache, encoding="utf-8") as fh:
            return json.load(fh)
    q = "&".join(f"{k}={v}" for k, v in params.items()) + "&api_key=" + KEY
    with urllib.request.urlopen(BASE + path + "?" + q, timeout=90) as r:
        data = json.load(r)
    os.makedirs(RAW, exist_ok=True)
    with open(cache, "w", encoding="utf-8") as fh:
        json.dump(data, fh)
    return data


def flares(win):
    out = {}
    for m in get("notifications", startDate=win["start"], endDate=win["end"], type="FLR"):
        body = m.get("messageBody", "")
        cls = re.search(r"Flare intensity:\s*([A-Z]\d+(?:\.\d+)?)\s*class", body)
        act = re.search(r"Activity ID:\s*(\S+?FLR-\d+)", body)
        if not cls or not act:
            continue
        peak = re.search(r"Flare peak time:\s*(\S+?)\.?\s", body)
        region = re.search(r"Source region:\s*([^\n(]+)", body)
        ar = re.search(r"Active Region (\d+)", body)
        out[act.group(1)] = {
            "id": act.group(1),
            "cls": cls.group(1),
            "peak": peak.group(1).rstrip(".") if peak else None,
            "location": region.group(1).strip() if region else None,
            "activeRegion": ar.group(1) if ar else None,
            "url": m.get("messageURL"),
        }
    return out


def class_value(cls):
    return {"A": 0.01, "B": 0.1, "C": 1, "M": 10, "X": 100}[cls[0]] * float(cls[1:] or 1)


def main():
    result = {"source": "NASA/CCMC DONKI via api.nasa.gov", "retrieved": date.today().isoformat(), "periods": []}
    for win in WINDOWS:
        fl = flares(win)
        sep = get("SEP", startDate=win["start"], endDate=win["end"]) or []
        gst = get("GST", startDate=win["start"], endDate=win["end"]) or []
        sep_flares = set()
        for e in sep:
            for l in e.get("linkedEvents") or []:
                if "FLR" in l.get("activityID", ""):
                    sep_flares.add(l["activityID"])
        events = []
        for f in sorted(fl.values(), key=lambda f: f["id"]):
            if f["cls"][0] not in "MX":
                continue
            particles = f["id"] in sep_flares
            v = class_value(f["cls"])
            # Gameplay strength 1-3 (documented simplification): M = 1, X = 2, X5+ or X with particles = 3
            strength = 1 if v < 100 else (3 if v >= 500 or particles else 2)
            events.append(dict(f, particles=particles, strength=strength))
        kp = max([k["kpIndex"] for g in gst for k in g.get("allKpIndex", [])] or [0])
        result["periods"].append(dict(win, flares=events, sepCount=len(sep), maxKp=kp))
        print(win["id"], len(events), "M/X flares,", len(sep), "SEP records, max Kp", kp)

    js = (
        "/* GENERATED by tools/fetch_donki.py - do not edit by hand.\n"
        " * Real solar events from NASA/CCMC DONKI (public domain). Replayed in-game for practice;\n"
        " * strength (1-3) is a simplified gameplay scale derived from flare class and particle events. */\n"
        "(function (root) {\n  const DATA = " + json.dumps(result, indent=1) + ";\n"
        "  if (typeof module === 'object' && module.exports) module.exports = DATA;\n"
        "  else root.OUTPOST_DONKI = DATA;\n})(typeof self !== 'undefined' ? self : this);\n"
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(js)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
