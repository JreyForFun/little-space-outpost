#!/usr/bin/env python3
"""Bundle a few real NASA Open Science Data Repository (OSDR) studies for the in-game Journal.

Usage:  python tools/fetch_osdr.py
Writes: src/data/osdr-studies.js   (window.OUTPOST_OSDR / module.exports)

Source: NASA OSDR search API, https://osdr.nasa.gov/osdr/data/search (public, no key needed).
The study title, accession, flight program, organism and release date come from OSDR. The short
"kid" summary next to each study is our own plain-language reading of the study title, labelled
as such in the game.
"""
import json
import os
import urllib.request
from datetime import date

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "data", "osdr-studies.js")
API = "https://osdr.nasa.gov/osdr/data/search?term={acc}&size=5&type=cgene"

# accession -> (journal id, kid summary written by us)
CURATED = {
    "OSD-342": ("osdr-bone", "Mice that lived on the Space Station lost muscle and bone. Scientists tested a treatment to protect them. Astronauts exercise every day for the same reason."),
    "OSD-412": ("osdr-veggie", "Astronauts grew leafy greens in the Space Station's Veggie garden. Scientists checked which tiny microbes lived on the plants, to keep space salad safe to eat."),
    "OSD-146": ("osdr-radiation", "Scientists studied how strong space-like radiation changes the tiny helpful microbes inside mice. It helps us understand why astronauts need shielding."),
}


def fetch(acc):
    with urllib.request.urlopen(API.format(acc=acc), timeout=60) as r:
        hits = json.load(r)["hits"]["hits"]
    for h in hits:
        s = h["_source"]
        if s.get("Accession") == acc:
            return s
    raise RuntimeError("study not found: " + acc)


def main():
    studies = []
    for acc, (jid, kid) in CURATED.items():
        s = fetch(acc)
        studies.append({
            "id": jid, "accession": acc, "title": s.get("Study Title", "").strip(),
            "flightProgram": s.get("Flight Program") or "Ground study", "organism": s.get("organism"),
            "released": s.get("Study Public Release Date"), "kid": kid,
            "url": "https://osdr.nasa.gov/bio/repo/data/studies/" + acc,
        })
        print(acc, "-", studies[-1]["title"][:80])
    data = {"source": "NASA Open Science Data Repository (OSDR)", "retrieved": date.today().isoformat(), "studies": studies}
    js = ("/* GENERATED by tools/fetch_osdr.py - real NASA OSDR study records (public). */\n"
          "(function (root) {\n  const DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"
          "  if (typeof module === 'object' && module.exports) module.exports = DATA;\n"
          "  else root.OUTPOST_OSDR = DATA;\n})(typeof self !== 'undefined' ? self : this);\n")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(js)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
